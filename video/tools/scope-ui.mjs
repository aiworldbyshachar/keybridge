// The app's own stylesheet for the film: ../src/renderer/style.css scoped to .kb -> assets/kb.css.
// :root, html and body become the .kb box; every rule only reaches inside a .kb; #id selectors match
// the data-id that tools/grab-ui.cjs leaves; the window's 100vh and fixed sheets fit the .kb box; the
// light theme only (no dark, no small-window rules); no CSS animations or transitions (the film must
// seek exactly); the UI faces are the film's local Segoe UI and Consolas.
//   node tools/scope-ui.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', '..', 'src', 'renderer', 'style.css');
const out = path.join(here, '..', 'assets', 'kb.css');

const css = fs.readFileSync(src, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

// top-level blocks: [prelude, body]
function blocks(text) {
  const list = [];
  let depth = 0;
  let start = 0;
  let open = -1;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '{') {
      if (depth === 0) open = i;
      depth++;
    } else if (text[i] === '}') {
      depth--;
      if (depth === 0) {
        list.push([text.slice(start, open).trim(), text.slice(open + 1, i)]);
        start = i + 1;
      }
    }
  }
  return list;
}

// split on commas that are not inside parentheses
function splitSelectors(s) {
  const parts = [];
  let depth = 0;
  let cur = '';
  for (const c of s) {
    if (c === '(') depth++;
    if (c === ')') depth--;
    if (c === ',' && depth === 0) {
      parts.push(cur.trim());
      cur = '';
    } else cur += c;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

function scopeSelector(sel) {
  sel = sel.replace(/#([a-z][a-z0-9-]*)/g, '[data-id="$1"]');
  if (sel === ':root' || sel === 'html' || sel === 'body') return ['.kb'];
  if (sel === '*') return ['.kb', '.kb *'];
  const dir = /^\[dir="(rtl|ltr)"\]\s*(.*)$/.exec(sel);
  if (dir) return [`.kb[dir="${dir[1]}"] ${dir[2]}`.trim()];
  return [`.kb ${sel}`];
}

function scopeBody(body) {
  return body
    .split(';')
    .map((d) => d.trim())
    .filter((d) => d && !/^(animation|transition)\s*:/.test(d) && !/^color-scheme\s*:/.test(d))
    .map((d) =>
      d
        .replace(/^--font\s*:.*$/s, '--font: "CB Sans", sans-serif')
        .replace(/^--mono\s*:.*$/s, '--mono: "CB Mono", monospace')
        .replace(/\b100vh\b/g, '100%')
        .replace(/^position\s*:\s*fixed$/, 'position: absolute'),
    )
    .map((d) => `  ${d};`)
    .join('\n');
}

const rules = [];
let dropped = 0;
for (const [prelude, body] of blocks(css)) {
  if (prelude.startsWith('@media') || prelude.startsWith('@keyframes')) {
    dropped++;
    continue;
  }
  if (prelude.startsWith('@')) throw new Error(`unexpected at-rule: ${prelude}`);
  const selectors = splitSelectors(prelude).flatMap(scopeSelector);
  rules.push(`${selectors.join(',\n')} {\n${scopeBody(body)}\n}`);
}

const header = `/* Generated by tools/scope-ui.mjs from src/renderer/style.css - don't edit; run it again. */
/* The scoped box: the window's own ground and face, and the place the app's fixed sheets sit in. */
.kb { position: absolute; inset: 0; overflow: hidden; }
`;
fs.writeFileSync(out, `${header}\n${rules.join('\n\n')}\n`);
console.log(`kb.css: ${rules.length} rules, ${dropped} @-blocks dropped (dark theme, small window, reduced motion, keyframes)`);
