fn emit(event: Value) {
    if let Some(events) = EVENTS.get() {
        let _ = events.send(event.to_string());
    }
}

fn trusted(prompt: bool) -> bool {
    unsafe {
        if !prompt {
            return AXIsProcessTrustedWithOptions(null()) != 0;
        }
        let keys = [kAXTrustedCheckOptionPrompt];
        let values = [kCFBooleanTrue];
        let options = CFDictionaryCreate(
            null(),
            keys.as_ptr(),
            values.as_ptr(),
            1,
            &kCFTypeDictionaryKeyCallBacks,
            &kCFTypeDictionaryValueCallBacks,
        );
        let ok = AXIsProcessTrustedWithOptions(options) != 0;
        CFRelease(options);
        ok
    }
}

/// Starts the tap on its own thread (it needs a run loop). Without the Accessibility permission it
/// asks once, reports {"event":"permission","accessibility":false} and waits until it's granted.
pub fn start(events: mpsc::Sender<String>) -> Result<(), String> {
    let _ = EVENTS.set(events);
    std::thread::spawn(|| unsafe {
        if !trusted(true) {
            emit(json!({"event": "permission", "accessibility": false}));
            while !trusted(false) {
                std::thread::sleep(Duration::from_secs(1));
            }
            emit(json!({"event": "permission", "accessibility": true}));
        }
        let mask = (1u64 << KEY_DOWN) | (1u64 << KEY_UP);
        let tap = CGEventTapCreate(SESSION_TAP, HEAD_INSERT, TAP_DEFAULT, mask, tap_proc, null_mut());
        if tap.is_null() {
            emit(json!({"event": "error", "message": "could not start the keyboard tap"}));
            return;
        }
        TAP.store(tap, SeqCst);
        let source = CFMachPortCreateRunLoopSource(null(), tap, 0);
        CFRunLoopAddSource(CFRunLoopGetCurrent(), source, kCFRunLoopCommonModes);
        CGEventTapEnable(tap, true);
        CFRunLoopRun();
    });
    Ok(())
}

unsafe extern "C" fn tap_proc(_proxy: *mut c_void, kind: u32, event: CGEventRef, _user: *mut c_void) -> CGEventRef {
    if kind == TAP_DISABLED_BY_TIMEOUT || kind == TAP_DISABLED_BY_USER {
        // macOS turns a slow tap off; turn it straight back on
        CGEventTapEnable(TAP.load(SeqCst), true);
        return event;
    }
    if kind == KEY_DOWN || kind == KEY_UP {
        let tag = CGEventGetIntegerValueField(event, FIELD_USER_DATA);
        if tag != OUR_INPUT {
            if on_key(event, kind == KEY_DOWN) {
                SWALLOW_COUNT.fetch_add(1, SeqCst);
                return null_mut();
            }
            if tag == SELFTEST_INPUT {
                return null_mut(); // the self-test's keys never reach the app in front
            }
        }
    }
    event
}

/// Decides one key event. Returns true to swallow it.
unsafe fn on_key(event: CGEventRef, down: bool) -> bool {
    let key = (CGEventGetIntegerValueField(event, FIELD_KEYCODE) as usize) & 0x7F;
    if !down {
        return SWALLOWED[key].swap(false, SeqCst);
    }
    if SWALLOWED[key].load(SeqCst) {
        return true; // auto-repeat of a hotkey we already took
    }
    if PAUSED.load(SeqCst) {
        return false;
    }
    let flags = CGEventGetFlags(event);
    let mods = modifiers(flags);
    let id = {
        let hotkeys = HOTKEYS.lock().unwrap();
        hotkeys.iter().find(|h| h.key == key as u32 && h.mods == mods).map(|h| h.id.clone())
    };
    if let Some(id) = id {
        SWALLOWED[key].store(true, SeqCst);
        FIRED.fetch_add(1, SeqCst);
        ABBREVS.lock().unwrap().reset();
        emit(json!({"event": "hotkey", "id": id}));
        return true;
    }
    abbrev_key(key, flags)
}

/// Feeds the abbreviation buffer. Returns true to swallow the key: the Space or Tab that fired one.
fn abbrev_key(key: usize, flags: u64) -> bool {
    let mut matcher = ABBREVS.lock().unwrap();
    if flags & (FLAG_CONTROL | FLAG_OPTION | FLAG_COMMAND) != 0 {
        matcher.reset(); // a Control / Option / Cmd combination, not typing
        return false;
    }
    let class = key_name(key as u32).map(key_class).unwrap_or(KeyClass::Other);
    let stroke = Stroke { key: key as u32, shift: flags & FLAG_SHIFT != 0 };
    let Some(fired) = matcher.press(stroke, class) else { return false };
    SWALLOWED[key].store(true, SeqCst);
    emit(json!({"event": "abbrev", "id": fired.id, "erase": fired.erase, "end": fired.end}));
    true
}

/// Left/right from the device-dependent flag bits (NX_DEVICE*KEYMASK). Events from tools that set
/// only the generic flag count as the left key.
fn modifiers(flags: u64) -> u32 {
    // (generic flag, left device bit, right device bit, left, right)
    const MAP: [(u64, u64, u64, u32, u32); 4] = [
        (0x0002_0000, 0x0002, 0x0004, SHIFT_LEFT, SHIFT_RIGHT),
        (0x0004_0000, 0x0001, 0x2000, CONTROL_LEFT, CONTROL_RIGHT),
        (0x0008_0000, 0x0020, 0x0040, ALT_LEFT, ALT_RIGHT),
        (0x0010_0000, 0x0008, 0x0010, META_LEFT, META_RIGHT),
    ];
    let mut mods = 0;
    for (generic, left_bit, right_bit, left, right) in MAP {
        if flags & generic == 0 {
            continue;
        }
        if flags & left_bit != 0 {
            mods |= left;
        }
        if flags & right_bit != 0 {
            mods |= right;
        }
        if flags & (left_bit | right_bit) == 0 {
            mods |= left;
        }
    }
    mods
}

/// Posts one key press. Flags are set explicitly, so Right Shift still held from the hotkey
/// doesn't turn the typed text into capitals.
unsafe fn post_key(keycode: u16, flags: u64, text: Option<&[u16]>, tag: i64) {
    for down in [true, false] {
        let event = CGEventCreateKeyboardEvent(null(), keycode, down);
        if event.is_null() {
            continue;
        }
        if let Some(units) = text {
            CGEventKeyboardSetUnicodeString(event, units.len(), units.as_ptr());
        }
        CGEventSetFlags(event, flags);
        CGEventSetIntegerValueField(event, FIELD_USER_DATA, tag);
        CGEventPost(HID_TAP, event);
        CFRelease(event);
    }
}

/// Backspaces for what an abbreviation left behind.
unsafe fn erase_keys(erase: usize) {
    for _ in 0..erase {
        post_key(KEY_DELETE, 0, None, OUR_INPUT);
    }
}

/// Left arrows that put the caret where {cursor} was.
unsafe fn left_keys(left: usize) {
    for _ in 0..left {
        post_key(KEY_LEFT, FLAGS_ARROW, None, OUR_INPUT);
    }
}

pub fn type_text(text: &str, erase: usize, left: usize) -> Result<(), String> {
    ABBREVS.lock().unwrap().reset();
    unsafe {
        erase_keys(erase);
        for ch in text.chars() {
            match ch {
                '\r' => {}
                '\n' => post_key(0x24, 0, None, OUR_INPUT),
                '\t' => post_key(0x30, 0, None, OUR_INPUT),
                _ => {
                    let mut units = [0u16; 2];
                    post_key(0, 0, Some(ch.encode_utf16(&mut units)), OUR_INPUT);
                }
            }
        }
        left_keys(left);
    }
    Ok(())
}

pub fn paste_text(text: &str, erase: usize, left: usize) -> Result<(), String> {
    ABBREVS.lock().unwrap().reset();
    let saved = pasteboard::save();
    pasteboard::write(&[vec![(TEXT_TYPE.to_string(), text.as_bytes().to_vec())]]);
    unsafe {
        erase_keys(erase);
        post_key(0x09, FLAG_COMMAND, None, OUR_INPUT); // Cmd + V
        left_keys(left);
    }
    std::thread::sleep(PASTE_SETTLE);
    pasteboard::write(&saved);
    Ok(())
}

fn cf_string(string: CFTypeRef) -> String {
    if string.is_null() {
        return String::new();
    }
    let mut buffer = [0 as c_char; 256];
    unsafe {
        if CFStringGetCString(string, buffer.as_mut_ptr(), buffer.len() as isize, UTF8) == 0 {
            return String::new();
        }
        CStr::from_ptr(buffer.as_ptr()).to_string_lossy().into_owned()
    }
}

/// The current keyboard input source, e.g. {"source":"com.apple.keylayout.Hebrew","locale":"he"}.
pub fn layout() -> Value {
    unsafe {
        let source = TISCopyCurrentKeyboardInputSource();
        if source.is_null() {
            return json!({"event": "layout", "source": "", "locale": ""});
        }
        let id = cf_string(TISGetInputSourceProperty(source, kTISPropertyInputSourceID));
        let languages = TISGetInputSourceProperty(source, kTISPropertyInputSourceLanguages);
        let locale = if !languages.is_null() && CFArrayGetCount(languages) > 0 {
            cf_string(CFArrayGetValueAtIndex(languages, 0))
        } else {
            String::new()
        };
        CFRelease(source);
        json!({"event": "layout", "source": id, "locale": locale})
    }
}

/// Typed `objc_msgSend` calls: each Objective-C signature needs its own function pointer type.
macro_rules! msg_fn {
    ($name:ident($($arg:ident: $ty:ty),*) -> $ret:ty) => {
        unsafe fn $name(target: Id, selector: &CStr $(, $arg: $ty)*) -> $ret {
            let send: unsafe extern "C" fn(Id, Sel $(, $ty)*) -> $ret =
                std::mem::transmute(objc_msgSend as unsafe extern "C" fn());
            send(target, sel_registerName(selector.as_ptr()) $(, $arg)*)
        }
    };
}
msg_fn!(msg() -> Id);
msg_fn!(msg_count() -> usize);
msg_fn!(msg_bytes() -> *const c_void);
msg_fn!(msg_index(index: usize) -> Id);
msg_fn!(msg_object(object: Id) -> Id);
msg_fn!(msg_set(object: Id, kind: Id) -> u8);
msg_fn!(msg_data(bytes: *const c_void, length: usize) -> Id);
msg_fn!(msg_array(objects: *const Id, count: usize) -> Id);
msg_fn!(msg_string(utf8: *const c_char) -> Id);
msg_fn!(msg_clear() -> isize);
msg_fn!(msg_write(objects: Id) -> u8);
msg_fn!(msg_release() -> ());

mod pasteboard {
    use super::*;

    /// One pasteboard item: its types and the data for each.
    pub type Item = Vec<(String, Vec<u8>)>;

    struct Pool(*mut c_void);
    impl Drop for Pool {
        fn drop(&mut self) {
            unsafe { objc_autoreleasePoolPop(self.0) };
        }
    }

    unsafe fn class(name: &CStr) -> Id {
        objc_getClass(name.as_ptr())
    }

    unsafe fn ns_string(s: &str) -> Id {
        let c = CString::new(s).unwrap_or_default();
        msg_string(class(c"NSString"), c"stringWithUTF8String:", c.as_ptr())
    }

    unsafe fn general() -> Id {
        msg(class(c"NSPasteboard"), c"generalPasteboard")
    }

    pub fn save() -> Vec<Item> {
        unsafe {
            let _pool = Pool(objc_autoreleasePoolPush());
            let items = msg(general(), c"pasteboardItems");
            if items.is_null() {
                return Vec::new();
            }
            let mut saved = Vec::new();
            for i in 0..msg_count(items, c"count") {
                let item = msg_index(items, c"objectAtIndex:", i);
                let types = msg(item, c"types");
                let mut entries = Vec::new();
                for j in 0..msg_count(types, c"count") {
                    let kind = msg_index(types, c"objectAtIndex:", j);
                    let data = msg_object(item, c"dataForType:", kind);
                    if data.is_null() {
                        continue;
                    }
                    let length = msg_count(data, c"length");
                    let bytes = msg_bytes(data, c"bytes") as *const u8;
                    let name = CStr::from_ptr(msg_bytes(kind, c"UTF8String") as *const c_char);
                    let copy = if length == 0 || bytes.is_null() {
                        Vec::new()
                    } else {
                        std::slice::from_raw_parts(bytes, length).to_vec()
                    };
                    entries.push((name.to_string_lossy().into_owned(), copy));
                }
                saved.push(entries);
            }
            saved
        }
    }

    /// Replaces the pasteboard with `items` plus the markers that tell clipboard tools to skip it.
    /// Also used to put the user's content back, so ClipBridge doesn't record it a second time.
    pub fn write(items: &[Item]) {
        unsafe {
            let _pool = Pool(objc_autoreleasePoolPush());
            let board = general();
            msg_clear(board, c"clearContents");
            let mut objects = Vec::new();
            for (n, entries) in items.iter().enumerate() {
                let item = msg(msg(class(c"NSPasteboardItem"), c"alloc"), c"init");
                for (kind, bytes) in entries {
                    let data = msg_data(class(c"NSData"), c"dataWithBytes:length:", bytes.as_ptr() as *const c_void, bytes.len());
                    msg_set(item, c"setData:forType:", data, ns_string(kind));
                }
                if n == 0 {
                    for marker in CLIPBOARD_MARKERS {
                        if !entries.iter().any(|(kind, _)| kind == marker) {
                            let data = msg_data(class(c"NSData"), c"dataWithBytes:length:", b"1".as_ptr() as *const c_void, 1);
                            msg_set(item, c"setData:forType:", data, ns_string(marker));
                        }
                    }
                }
                objects.push(item);
            }
            if !objects.is_empty() {
                let array = msg_array(class(c"NSArray"), c"arrayWithObjects:count:", objects.as_ptr(), objects.len());
                msg_write(board, c"writeObjects:", array);
            }
            for item in objects {
                msg_release(item, c"release");
            }
        }
    }
}

/// Posts F19 (a key no app reacts to) once with Right Shift held and once with Left Shift held,
/// with a hotkey on Right Shift + F19, and checks the first was taken and swallowed and the second
/// passed. Then types ";q" + Space with an abbreviation on ";q" and checks it fired and the Space
/// was taken. None of these keys reach the app in front.
pub fn selftest() -> i32 {
    let fail = |reason: &str| {
        println!("{}", json!({"selftest": "fail", "reason": reason}));
        1
    };
    if !trusted(true) {
        return fail("needs the Accessibility permission (System Settings > Privacy & Security > Accessibility)");
    }
    let (events, received) = mpsc::channel();
    let _ = start(events);
    for _ in 0..40 {
        if !TAP.load(SeqCst).is_null() {
            break;
        }
        std::thread::sleep(Duration::from_millis(50));
    }
    if TAP.load(SeqCst).is_null() {
        return fail("the keyboard tap didn't start");
    }
    let f19 = key_code("F19").unwrap();
    set_hotkeys(vec![Hotkey { id: "selftest".into(), mods: SHIFT_RIGHT, key: f19 }]);
    let (semicolon, q, space) = (key_code("Semicolon").unwrap(), key_code("KeyQ").unwrap(), key_code("Space").unwrap());
    let stroke = |key| Stroke { key, shift: false };
    set_abbrevs(vec![Abbrev { id: "selftest".into(), keys: vec![stroke(semicolon), stroke(q)], word: false }]);
    unsafe {
        post_key(f19 as u16, 0x0002_0004, None, SELFTEST_INPUT); // Right Shift held
        post_key(f19 as u16, 0x0002_0002, None, SELFTEST_INPUT); // Left Shift held
        for key in [semicolon, q, space] {
            post_key(key as u16, 0, None, SELFTEST_INPUT);
        }
    }
    let mut got = Vec::new();
    let deadline = Instant::now() + Duration::from_secs(2);
    while got.len() < 2 {
        match received.recv_timeout(deadline.saturating_duration_since(Instant::now())) {
            Ok(event) => got.push(event),
            Err(_) => break,
        }
    }
    std::thread::sleep(Duration::from_millis(300));

    let fired = FIRED.load(SeqCst);
    let swallowed = SWALLOW_COUNT.load(SeqCst);
    let hotkey = got.iter().any(|e| e.contains(r#""event":"hotkey""#) && e.contains(r#""id":"selftest""#));
    let abbrev = got.iter().any(|e| e.contains(r#""event":"abbrev""#) && e.contains(r#""erase":2"#));
    // swallowed: the hotkey's F19 down and up, the abbreviation's Space down and up
    let ok = fired == 1 && swallowed == 4 && hotkey && abbrev;
    println!(
        "{}",
        json!({"selftest": if ok { "pass" } else { "fail" }, "fired": fired, "swallowed": swallowed, "hotkey": hotkey, "abbrev": abbrev})
    );
    if ok { 0 } else { 1 }
}
